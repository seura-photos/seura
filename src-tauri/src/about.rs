//! About Seura Photos (SET-5): the version, a line saying it's an early
//! build while below 1.0, and links to the website, the project, and the
//! license. On Windows the UI shows it in a dialog from the toolbar's ⋯
//! button; on macOS it's the system's About panel, from the app menu
//! (ACC-4).

use serde::Deserialize;
use specta::Type;

/// The app's version, from `Cargo.toml`.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// A link in About. The UI names one of these rather than passing an
/// address, so it can't open any other.
#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq, Type)]
#[serde(rename_all = "camelCase")]
pub enum Link {
    Website,
    Project,
    License,
}

impl Link {
    #[cfg(test)]
    pub const ALL: [Link; 3] = [Link::Website, Link::Project, Link::License];

    pub fn url(self) -> &'static str {
        match self {
            Link::Website => "https://seuraphotos.app",
            Link::Project => "https://github.com/seura-photos/seura",
            Link::License => "https://github.com/seura-photos/seura/blob/main/LICENSE",
        }
    }
}

/// The third-party notices bundled with the app (SET-5), generated by
/// `npm run notices` and installed beside it as a resource.
pub fn notices<R: tauri::Runtime>(app: &tauri::AppHandle<R>) -> Result<std::path::PathBuf, String> {
    use tauri::Manager;

    let path = app
        .path()
        .resolve(NOTICES, tauri::path::BaseDirectory::Resource)
        .map_err(|error| error.to_string())?;
    if path.is_file() {
        Ok(path)
    } else {
        Err(format!("{} is missing", path.display()))
    }
}

/// The notices' file name, as `tauri.conf.json` installs it.
const NOTICES: &str = "third-party-notices.txt";

/// What the system's About panel shows besides the name, icon, and
/// copyright, which it takes from the app bundle. The panel shows its
/// credits as plain text, so the links are there as addresses, not to
/// click. The license's is left out: the bundle's copyright line already
/// names the Apache License 2.0, and the address wrapped.
#[cfg(target_os = "macos")]
pub fn metadata() -> tauri::menu::AboutMetadata<'static> {
    use crate::messages::t;

    let mut credits = Vec::new();
    // An early build, before the beta: any version below 1.0.
    if VERSION.starts_with("0.") {
        credits.push(t("about-early-build"));
        credits.push(String::new());
    }
    credits.extend(
        [Link::Website, Link::Project]
            .map(|link| link.url().trim_start_matches("https://").to_string()),
    );
    tauri::menu::AboutMetadata {
        version: Some(VERSION.to_string()),
        // The build number, which the panel shows in parentheses after the
        // version and otherwise takes from the bundle, where it's the same:
        // "Version 0.2.1 (0.2.1)". Empty, it shows none.
        short_version: Some(String::new()),
        credits: Some(credits.join("\n")),
        ..Default::default()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The notices are bundled under the name `notices` resolves (SET-5),
    /// and generated rather than missing.
    #[test]
    fn the_notices_are_bundled_under_the_name_about_opens() {
        let config: serde_json::Value =
            serde_json::from_str(include_str!("../tauri.conf.json")).unwrap();
        let resources = &config["bundle"]["resources"];
        assert_eq!(resources["notices/third-party-notices.txt"], NOTICES);
        let notices = include_str!("../notices/third-party-notices.txt");
        assert!(notices.starts_with("Third-party notices for Seura Photos"));
    }

    #[test]
    fn every_link_is_secure_and_seuras_own() {
        for link in Link::ALL {
            let url = link.url();
            assert!(
                url == "https://seuraphotos.app"
                    || url.starts_with("https://github.com/seura-photos/seura"),
                "{url}"
            );
        }
    }
}
